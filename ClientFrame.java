    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        

                                        
    // Clear the text area and set header
    jTextArea1.setText("====== Clients List ======\n\n");
    
    // Initialize variables for traversal
    Node current = MainClass.company.headClient;
    int clientCount = 1;
    
    // Loop through all clients
    while(current != null) {
        // Append client number and details
        jTextArea1.append("Client #" + clientCount++ + "\n");
        jTextArea1.append(current.getData().toString() + "\n\n");
        
        // Move to next client
        current = current.getNext();
    }
    
    // Append footer with total count
    jTextArea1.append("Total Clients: " + MainClass.company.CountClient() + "\n");
    jTextArea1.append("==========================");
}
                                         
   
                                   
    
