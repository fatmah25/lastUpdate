    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
// find
    // عرض مربع حوار لإدخال البريد الإلكتروني
    String email = JOptionPane.showInputDialog(this, "Enter Client Email to find:");
    
    if (email != null && !email.trim().isEmpty()) { // التأكد من أن المستخدم لم يضغط إلغاء أو ترك الحقل فارغاً
        Client client = MainClass.company.findClient(email.trim());
        
        if (client != null) {
            JOptionPane.showMessageDialog(this, client.toString(), "Client Info", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Client not found.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }


    }//GEN-LAST:event_jButton4ActionPerformed

