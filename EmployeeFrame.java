    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
//add
    try {
        // 1. Get basic info
        String name = jTextField3.getText();
        if (name.equals("")) {
            JOptionPane.showMessageDialog(this, "Please enter employee name!");
            return;
        }

        int id;
        try {
            id = Integer.parseInt(jTextField4.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID must be a number!");
            return;
        }

        double salary;
        try {
            salary = Double.parseDouble(jTextField1.getText()); // Assuming jTextField5 is for salary
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Salary must be a number!");
            return;
        }

        // 2. Check duplicate ID
        for (Employee emp : MainClass.company.employeesList) {
            if (emp != null && emp.getId() == id) {
                JOptionPane.showMessageDialog(this, "This ID already exists!");
                return;
            }
        }

        // 3. Get employee type
        String type = (String) jComboBox1.getSelectedItem();
        Employee newEmp = null;

        if (type.equals("Manager")) {
            // Manager data
            int projects = Integer.parseInt(JOptionPane.showInputDialog(this, "Enter number of projects:"));
            int teamSize = Integer.parseInt(JOptionPane.showInputDialog(this, "Enter team size:"));
            newEmp = new Manager(name, id, salary, projects, teamSize);
            
        } else if (type.equals("Developer")) {
            // Developer data
            int rank = Integer.parseInt(JOptionPane.showInputDialog(this, "Enter developer rank (1-10):"));
            
            // Developer type selection
            String[] options = {"Application", "Web"};
            int choice = JOptionPane.showOptionDialog(this, 
                "Select developer type:", 
                "Developer Type",
                JOptionPane.DEFAULT_OPTION, 
                JOptionPane.QUESTION_MESSAGE,
                null, options, options[0]);
            
            if (choice == 0) { // Application Developer
                String platform = JOptionPane.showInputDialog(this, "Enter platform (I/W):");
                
                
           
if (!platform.equalsIgnoreCase("I") && !platform.equalsIgnoreCase("W")) {
    JOptionPane.showMessageDialog(this, "Invalid platform! Please enter 'I' or 'W'.");
    return;
}
                
                
                
                String security = JOptionPane.showInputDialog(this, "Enter security level (high/medium/low):");
                newEmp = new Applications_developer(name, id, salary, rank, platform, security);
                
if (!security.equalsIgnoreCase("high") && !security.equalsIgnoreCase("medium") && !security.equalsIgnoreCase("low")) {
    JOptionPane.showMessageDialog(this, "Invalid security level! Please enter 'high', 'medium' or 'low'.");
    return;
}
                
                
                
                
                
                
                
                
                
                
            } else { // Web Developer
                double score = Double.parseDouble(JOptionPane.showInputDialog(this, "Enter performance score (0-100):"));
                boolean darkMode = JOptionPane.showConfirmDialog(this, "Supports dark mode?") == JOptionPane.YES_OPTION;
                newEmp = new Web_developer(name, id, salary, rank, "W", score, darkMode);
            }
        }

        // 4. Add employee
        MainClass.company.addEmployee(newEmp);
        JOptionPane.showMessageDialog(this, "Employee added successfully!");
        
        // 5. Clear fields
        jTextField3.setText("");
        jTextField4.setText("");
        jTextField1.setText(""); // Clear salary field too
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }


        
        
        

    }//GEN-LAST:event_jButton4ActionPerformed
     
    
